import json
import re

import numpy as np

from gpsfree.evaluate import fail_threshold_m, load_suite, suite_fingerprint
from gpsfree.paths import EXPERIMENTS

START, END = "<!-- leaderboard:start -->", "<!-- leaderboard:end -->"


def render() -> str:
    """One table per platform; methods ranked by mean over worlds of the headline median error."""
    suite = load_suite()
    head = f"median_err_{suite['headline_m']}m"
    current = suite_fingerprint()
    results = [json.loads(p.read_text()) for p in sorted(EXPERIMENTS.glob("*/results.json"))]
    groups = sorted({g for r in results for g in r["summary"]})
    platforms = sorted({g.split("/")[1] for g in groups})

    lines = [
        f"Median 3D error (m) after {suite['headline_m']} m travelled; fail rate "
        f"(> {fail_threshold_m(suite):g} m) in brackets. Lower is better. Suite `{current}`. "
        "Generated by `uv run gpsfree leaderboard`; do not edit.",
    ]
    for platform in platforms:
        worlds = [g.split("/")[0] for g in groups if g.endswith(f"/{platform}")]
        rows = [r for r in results if any(f"{w}/{platform}" in r["summary"] for w in worlds)]

        def rank_key(r):
            vals = [r["summary"].get(f"{w}/{platform}", {}).get(head) for w in worlds]
            vals = [v for v in vals if v is not None]
            return (r["suite"] != current, np.mean(vals) if vals else np.inf)

        lines += ["", f"### {platform}", "",
                  "| # | method | author | " + " | ".join(worlds) + " |",
                  "|---|---|---|" + "---|" * len(worlds)]
        for rank, r in enumerate(sorted(rows, key=rank_key), 1):
            cells = []
            for w in worlds:
                s = r["summary"].get(f"{w}/{platform}")
                cells.append("—" if s is None or s.get(head) is None else f"{s[head]:.1f} ({s['fail_rate']:.0%})")
            name = f"[{r['experiment']}](experiments/{r['experiment']})" + (" ⚠ stale" if r["suite"] != current else "")
            lines.append(f"| {rank} | {name} | {r.get('author') or ''} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def update_readme(text: str, table: str) -> str:
    block = f"{START}\n{table}{END}"
    if START not in text:
        return text.rstrip("\n") + f"\n\n## Leaderboard\n\n{block}\n"
    return re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
