import json

import numpy as np

from gpsfree.evaluate import load_suite, suite_fingerprint
from gpsfree.paths import EXPERIMENTS


def render() -> str:
    suite = load_suite()
    head = f"median_err_{suite['headline_m']}m"
    current = suite_fingerprint()
    rows, groups = [], set()
    for path in sorted(EXPERIMENTS.glob("*/results.json")):
        r = json.loads(path.read_text())
        groups |= set(r["summary"])
        rows.append(r)
    groups = sorted(groups)

    def rank_key(r):
        vals = [r["summary"].get(g, {}).get(head) for g in groups]
        vals = [v for v in vals if v is not None]
        return (r["suite"] != current, np.mean(vals) if vals else np.inf)

    lines = [
        "# Leaderboard",
        "",
        f"Median horizontal error (m) after {suite['headline_m']} m travelled, fail rate (> {suite['fail_threshold_m']} m) in brackets. "
        f"Lower is better. Generated by `uv run gpsfree leaderboard`; do not edit.",
        "",
        "| experiment | author | " + " | ".join(groups) + " |",
        "|---|---|" + "---|" * len(groups),
    ]
    for r in sorted(rows, key=rank_key):
        cells = []
        for g in groups:
            s = r["summary"].get(g)
            cells.append("—" if s is None or s.get(head) is None else f"{s[head]:.1f} ({s['fail_rate']:.0%})")
        name = r["experiment"] + (" ⚠ stale" if r["suite"] != current else "")
        lines.append(f"| {name} | {r.get('author') or ''} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"
