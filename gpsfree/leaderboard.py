import json
import re

from gpsfree.algorithm import Algorithm
from gpsfree.evaluate import is_stale, load_algorithm, load_suite, suite_groups
from gpsfree.paths import EXPERIMENTS, HARDWARE

START, END = "<!-- leaderboard:start -->", "<!-- leaderboard:end -->"
MAX_COST_USD = 3000  # hardware must cost less than this to be verified and ranked
TOP_N = 5


def render() -> str:
    """One table per world/platform group in the suite, methods ranked by score (geometric-mean 3D error)."""
    suite = load_suite()
    results = [json.loads(p.read_text()) for p in sorted(EXPERIMENTS.glob("*/results.json"))]
    bands = [f"{lo}+" if i == len(suite["mae_bands_m"]) - 1 else f"{lo}-{suite['mae_bands_m'][i + 1]}"
             for i, lo in enumerate(suite["mae_bands_m"])]

    lines = [f"Score = geometric-mean 3D error along the route (lower is better). Top {TOP_N} methods with hardware "
             f"under ${MAX_COST_USD:,}, per world. Generated by `uv run gpsfree leaderboard`; do not edit."]
    for g in suite_groups():
        rows = sorted((r for r in results if g in r["summary"] and within_budget(r["experiment"])),
                      key=lambda r: (is_stale(r, g), r["summary"][g]["score_log10"]))[:TOP_N]
        lines += ["", f"### {g}", "",
                  f"| # | method | hardware | cost (USD) | author | score (m) | log₁₀ | lost at (m) | growth k | "
                  + " | ".join(f"MAE {b} m" for b in bands) + " |",
                  "|---|---|---|---|---|---|---|---|---|" + "---|" * len(bands)]
        for rank, r in enumerate(rows, 1):
            s = r["summary"][g]
            name = f"[{r['experiment']}](experiments/{r['experiment']})" + (" ⚠ stale" if is_stale(r, g) else "")
            mae = [_fmt(s["mae_m"].get(b)) for b in bands]
            lines.append(f"| {rank} | {name} | {r.get('hardware') or 'suite default'} | {_cost(hardware_cost(r['experiment']))} | {r.get('author') or ''} | {_fmt(s['score_m'])} | {s['score_log10']:.2f} | "
                         f"{s['lost_at_m']:.0f} | {_fmt(s['growth_k'])} | " + " | ".join(mae) + " |")
        if not rows:
            lines.append("| | *no results yet* |" + " |" * (7 + len(bands)))
    return "\n".join(lines) + "\n"


def hardware_cost(experiment: str) -> float | None:
    """Price of the profile parts the method uses: the IMU, plus the magnetometer if it implements on_mag.
    Suite-default sensors (and baro/echo) have no price."""
    algo = load_algorithm(experiment)
    if algo.hardware is None:
        return None
    hw = json.loads((HARDWARE / f"{algo.hardware}.json").read_text())
    parts = [hw["imu"]] + ([hw["mag"]] if algo.on_mag is not Algorithm.on_mag else [])
    return sum(p["price_usd"] for p in parts)


def within_budget(experiment: str) -> bool:
    cost = hardware_cost(experiment)
    return cost is None or cost < MAX_COST_USD


def _cost(v):
    return "—" if v is None else f"{v:,.0f}"


def _fmt(v):
    return "—" if v is None else f"{v:,.1f}"


def update_readme(text: str, table: str) -> str:
    block = f"{START}\n{table}{END}"
    if START not in text:
        return text.rstrip("\n") + f"\n\n## Leaderboard\n\n{block}\n"
    return re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
