import json
import re

from gpsfree.algorithm import Algorithm
from gpsfree.evaluate import load_algorithm, load_scenario, load_suite, suite_fingerprint, suite_scenarios
from gpsfree.paths import EXPERIMENTS, HARDWARE, RANGERS

START, END = "<!-- leaderboard:start -->", "<!-- leaderboard:end -->"
MAX_COST_USD = 3000  # hardware must cost less than this to be verified and ranked
TOP_N = 5


def render() -> str:
    """Overall table (top N under the cost cap) plus a methods x scenarios matrix of scores."""
    suite = load_suite()
    current = suite_fingerprint()
    results = [json.loads(p.read_text()) for p in sorted(EXPERIMENTS.glob("*/results.json"))]
    results = [r for r in results if "overall" in r.get("summary", {}) and within_budget(r["experiment"])]
    results.sort(key=lambda r: (r["suite"] != current, r["summary"]["overall"]["score_log10"]))
    top = results[:TOP_N]
    scen = suite_scenarios(suite)

    lines = [f"Score = geometric mean over {len(scen)} scenarios of each scenario's median geometric-mean 3D error "
             f"({suite['runs_per_scenario']} runs per scenario; lower is better). Top {TOP_N} methods with hardware under "
             f"${MAX_COST_USD:,}, counting every sensor the method uses. Integrity columns need a method that reports "
             f"an uncertainty radius: *misleading* = share of time the true error lies outside its 95% radius, "
             f"*silent* = share of runs that were off by more than {suite['lost_threshold_m']:g} m while claiming to be "
             f"within it. Suite `{current}`. Generated by `uv run gpsfree leaderboard`; do not edit.", "",
             "| # | method | how it works | sensors | cost (USD) | author | score (m) | worst scenario (m) | runs lost | misleading | silent |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for rank, r in enumerate(top, 1):
        o = r["summary"]["overall"]
        lines.append(f"| {rank} | {_name(r, current)} | {summary(r['experiment'])} | {_sensors(r)} | {_cost(hardware_cost(r['experiment']))} | "
                     f"{r.get('author') or ''} | {_fmt(o['score_m'])} | {o['worst_scenario']} {_fmt(o['worst_score_m'])} | "
                     f"{o['lost_frac']:.0%} | {_pct(o.get('misleading_frac'))} | {_pct(o.get('silent_failure_frac'))} |")
    lines += ["", "**Per scenario** (median score in m; share of runs lost in brackets)", "",
              "| method | " + " | ".join(load_scenario(s)["name"] for s in scen) + " |",
              "|---|" + "---|" * len(scen)]
    for r in top:
        cells = []
        for s in scen:
            x = r["summary"].get(s)
            cells.append("—" if x is None else f"{_fmt(x['score_m'])} ({x['lost_frac']:.0%})")
        lines.append(f"| {r['experiment']} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def summary(experiment: str) -> str:
    """The one-sentence **Summary.** line of the experiment's README card, if it has one."""
    card = EXPERIMENTS / experiment / "README.md"
    if card.exists():
        for line in card.read_text().splitlines():
            if line.startswith("**Summary.**"):
                return line.removeprefix("**Summary.**").strip().replace("|", "/")
    return ""


def _name(r, current):
    return f"[{r['experiment']}](experiments/{r['experiment']})" + (" ⚠ stale" if r["suite"] != current else "")


def _sensors(r):
    algo = load_algorithm(r["experiment"])
    parts = [r.get("hardware") or "suite IMU"]
    if algo.on_echo is not Algorithm.on_echo:
        parts.append(r.get("ranger") or load_suite()["default_ranger"])
    return " + ".join(parts)


def hardware_cost(experiment: str) -> float | None:
    """Price of the parts the method uses: the profile IMU, the magnetometer if it implements on_mag,
    and the ranger if it implements on_echo. Suite-default IMU/mag and the barometer have no price."""
    algo = load_algorithm(experiment)
    total, priced = 0.0, False
    if algo.hardware is not None:
        hw = json.loads((HARDWARE / f"{algo.hardware}.json").read_text())
        total += hw["imu"]["price_usd"] + (hw["mag"]["price_usd"] if algo.on_mag is not Algorithm.on_mag else 0)
        priced = True
    if algo.on_echo is not Algorithm.on_echo:
        ranger = algo.ranger or load_suite()["default_ranger"]
        total += json.loads((RANGERS / f"{ranger}.json").read_text())["price_usd"]
        priced = True
    return total if priced else None


def within_budget(experiment: str) -> bool:
    cost = hardware_cost(experiment)
    return cost is None or cost < MAX_COST_USD


def _cost(v):
    return "—" if v is None else f"{v:,.0f}"


def _fmt(v):
    return "—" if v is None else (f"{v:,.0f}" if v >= 100 else f"{v:,.1f}")


def _pct(v):
    return "no claim" if v is None else f"{v:.0%}"


def update_readme(text: str, table: str) -> str:
    block = f"{START}\n{table}{END}"
    if START not in text:
        return text.rstrip("\n") + f"\n\n## Leaderboard\n\n{block}\n"
    return re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
